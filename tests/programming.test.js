'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const timeline = require('../lib/schedule')
const p = require('../lib/programming')
const id = i => `00000000-0000-4000-8000-${String(i).padStart(12, '0')}`
const video = (i, sec = 30) => ({ uuid: id(i), name: `Video ${i}`, duration: sec, isLive: false,
  state: 1, channelName: 'Channel', publishedAt: '2026-10-01T00:00:00Z', playable: true })
function ready (at = 0) {
  const state = timeline.createState(0)
  state.queue = [video(1), video(2), video(3)]
  state.anchorAt = 0
  state.anchorUuid = id(1)
  p.ensureProgramming(state)
  p.updateAuto(state, state.queue)
  return state
}
test('reorder only upcoming video UUIDs; player retains UUID and offset', () => {
  const s = ready()
  const before = timeline.currentVod(s, 45000)
  assert.equal(before.video.uuid, id(2))
  p.reorder(s, [id(1), id(3)], 45000)
  const after = timeline.currentVod(s, 45000)
  assert.equal(after.video.uuid, id(2))
  assert.equal(after.offset, before.offset)
  assert.deepEqual(s.queue.map(x => x.uuid), [id(2), id(1), id(3)])
  assert.throws(() => p.reorder(s, [id(3)], 45000), /exactly/)
})
test('scheduled playlists play only when current active queue finishes, in saved order, then auto resumes', () => {
  const s = ready()
  p.addPlaylist(s, { id: 'evening', name: 'Evening', items: [video(4, 20), video(5, 25)] })
  p.addPlaylist(s, { id: 'night', name: 'Night', items: [video(6, 10)] })
  p.schedule(s, 'evening', 45000, 'session1')
  p.schedule(s, 'night', 45000, 'session2')
  assert.equal(s.programming.endsAt, 90000)
  assert.equal(p.advance(s, 89999), false)
  assert.equal(p.advance(s, 90000), true)
  assert.equal(s.queue[0].uuid, id(4))
  assert.equal(timeline.currentVod(s, 95000).offset, 5)
  assert.equal(s.programming.endsAt, 135000)
  assert.equal(p.advance(s, 135000), true)
  assert.equal(s.queue[0].uuid, id(6))
  assert.equal(s.programming.endsAt, 145000)
  assert.equal(p.advance(s, 145000), true)
  assert.equal(s.programming.active.type, 'auto')
  assert.equal(s.programming.endsAt, null)
  assert.equal(s.queue[0].uuid, id(1))
})
test('upcoming reorder with scheduled transition shifts EPG without resetting active playback', () => {
  const s = ready()
  p.addPlaylist(s, { id: 'show', name: 'Show', items: [video(4, 45)] })
  p.schedule(s, 'show', 45000, 'session')
  assert.deepEqual(p.adminStatus(s, 45000).upcoming.map(x => x.uuid), [id(3)])
  const before = timeline.currentVod(s, 45000)
  p.reorder(s, [id(3)], 45000)
  assert.equal(timeline.currentVod(s, 45000).offset, before.offset)
  assert.equal(s.programming.endsAt, 90000)
  assert.equal(p.adminStatus(s, 45000).pending[0].startsAt, 90000)
})
test('saved playlists can be reordered, cancelled or deleted without altering the active queue', () => {
  const s = ready()
  p.addPlaylist(s, { id: 'a', name: 'A', items: [video(4)] })
  p.addPlaylist(s, { id: 'b', name: 'B', items: [video(5)] })
  p.schedule(s, 'a', 1000, 's1')
  p.schedule(s, 'b', 1000, 's2')
  const before = timeline.currentVod(s, 1000)
  p.reorderScheduled(s, ['s2', 's1'])
  p.deletePlaylist(s, 'a')
  assert.deepEqual(s.programming.pending.map(x => x.playlistId), ['b', 'a'], 'snapshots survive template deletion')
  p.unschedule(s, 's1')
  assert.equal(s.programming.pending.length, 1)
  assert.equal(timeline.currentVod(s, 1000).video.uuid, before.video.uuid)
  assert.throws(() => p.reorderScheduled(s, ['s1', 's2']), /Invalid/)
})
test('live preemption keeps scheduled playlist waiting, new public VOD first after live', () => {
  const s = ready()
  p.addPlaylist(s, { id: 'custom', name: 'Custom', items: [video(5, 40)] })
  p.schedule(s, 'custom', 10000, 'slot')
  const originalEnd = s.programming.endsAt
  const active = { ...video(7, 0), isLive: true, state: 1 }
  timeline.applyLive(s, [active], 15000)
  const newPublic = { ...video(4, 12), publishedAt: new Date(20000).toISOString() }
  p.mergeDuringLive(s, [newPublic])
  assert.equal(p.advance(s, originalEnd + 100000), false)
  timeline.applyLive(s, [], 30000)
  p.extendAfterLive(s, 30000)
  assert.equal(s.queue[0].uuid, id(4))
  assert.ok(s.programming.endsAt > 30000)
  assert.equal(s.programming.pending.length, 1)
})
test('reject invalid playlists and retain stored programming across state migration', () => {
  const s = ready()
  assert.throws(() => p.addPlaylist(s, { id: 'x', name: '', items: [video(3)] }), /name/)
  assert.throws(() => p.addPlaylist(s, { id: 'x', name: 'X', items: [video(3), video(3)] }), /duplicate/)
  assert.throws(() => p.addPlaylist(s, { id: 'x', name: 'X', items: [] }), /1–100/)
  const rebooted = JSON.parse(JSON.stringify(s))
  assert.equal(p.ensureProgramming(rebooted).revision, 0)
})
test('public EPG shows the saved playlist after current cycle rather than looping old VODs', () => {
  const s = ready()
  p.addPlaylist(s, { id: 'x', name: 'Evening', items: [video(4, 40), video(5, 25)] })
  p.schedule(s, 'x', 45000, 'session1')
  const result = p.publicSchedule(s, timeline.status(s, 45000), 8)
  assert.deepEqual(result.upcoming.map(v => v.uuid), [id(3), id(4), id(5)])
  assert.equal(result.upcoming[1].startsAt, 90000)
  assert.equal(result.upcoming[2].startsAt, 130000)
  assert.deepEqual(result.nextPlaylists, [{ name: 'Evening', count: 2 }])
})
